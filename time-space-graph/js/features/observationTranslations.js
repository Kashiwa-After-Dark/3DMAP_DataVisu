const translations = new Map(phrases.flatMap(([aliases, english]) => aliases.split("|").map((phrase) => [phrase, english])));
const orderedPhrases = [...translations].sort(([a], [b]) => b.length - a.length);

export function translateObservationText(value) {
  const text = String(value || "").trim();
  if (translations.has(text)) return translations.get(text);
  // Match against the original string once; translated words are never replaced again.
  let result = "";
  for (let offset = 0; offset < text.length;) {
    const match = orderedPhrases.find(([phrase]) => text.startsWith(phrase, offset));
    if (match) {
      result += match[1];
      offset += match[0].length;
    } else {
      result += text[offset++];
    }
  }
  return result.replaceAll("、", "; ").replaceAll("・", " / ").replaceAll("。", ". ");
}
